-- Complete administrative backoffice: governance, moderation and auditability.
BEGIN;
SET LOCAL lock_timeout = '10s';

ALTER TABLE public.clients
  ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS blocked_reason text;
ALTER TABLE public.partner
  ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS blocked_reason text,
  ADD COLUMN IF NOT EXISTS trade_license text,
  ADD COLUMN IF NOT EXISTS document_url text,
  ADD COLUMN IF NOT EXISTS approval_reason text,
  ADD COLUMN IF NOT EXISTS approved_at timestamptz,
  ADD COLUMN IF NOT EXISTS approved_by text;
ALTER TABLE public.reviews
  ADD COLUMN IF NOT EXISTS moderation_status text NOT NULL DEFAULT 'published'
    CHECK (moderation_status IN ('published','hidden','flagged')),
  ADD COLUMN IF NOT EXISTS moderation_reason text,
  ADD COLUMN IF NOT EXISTS moderated_at timestamptz,
  ADD COLUMN IF NOT EXISTS moderated_by text;

-- Keep the database constraint aligned with the workflow status union. Older
-- installations were created before partner rejection became a terminal state.
ALTER TABLE public.repair_orders
  DROP CONSTRAINT IF EXISTS repair_orders_status_check;
ALTER TABLE public.repair_orders
  ADD CONSTRAINT repair_orders_status_check CHECK (status IN
    ('pending','quoted','approved','in_progress','waiting_parts','ready','completed','rejected','cancelled'));

CREATE TABLE IF NOT EXISTS public.admin_roles (
  account_id bigint NOT NULL,
  account_role text NOT NULL CHECK (account_role IN ('client','partner')),
  role text NOT NULL DEFAULT 'analyst'
    CHECK (role IN ('owner','manager','analyst','support','finance','logistics')),
  permissions jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(permissions) = 'array'),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (account_id, account_role)
);

CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id text NOT NULL,
  actor_role text NOT NULL,
  action text NOT NULL,
  entity_type text NOT NULL,
  entity_id text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS admin_audit_logs_created_at
  ON public.admin_audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_logs_entity
  ON public.admin_audit_logs(entity_type, entity_id);

ALTER TABLE public.admin_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.admin_audit_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.admin_roles, public.admin_audit_logs FROM PUBLIC;
DO $$
DECLARE browser_role text;
BEGIN
  FOREACH browser_role IN ARRAY ARRAY['anon', 'authenticated']
  LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = browser_role) THEN
      EXECUTE format(
        'REVOKE ALL ON public.admin_roles, public.admin_audit_logs FROM %I',
        browser_role
      );
    END IF;
  END LOOP;
END $$;

COMMIT;
